CREATE SCHEMA IF NOT EXISTS pasor_kita;
REVOKE ALL ON SCHEMA pasor_kita FROM PUBLIC;
CREATE TABLE IF NOT EXISTS pasor_kita.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(30) NOT NULL DEFAULT 'member' CHECK (role IN ('member','admin')),
  campus VARCHAR(30) NOT NULL CHECK (campus IN ('Parit Raja','Pagoh')) DEFAULT 'Parit Raja',
  card_color VARCHAR(30) NOT NULL DEFAULT 'burgundy' CHECK (card_color IN ('burgundy','forest','navy')),
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pasor_kita.categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  description VARCHAR(160) NOT NULL DEFAULT '',
  icon VARCHAR(20) NOT NULL DEFAULT 'others'
);
CREATE TABLE IF NOT EXISTS pasor_kita.businesses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL,
  name VARCHAR(80) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (owner_id) REFERENCES pasor_kita.users(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.verification_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id INTEGER NOT NULL,
  type VARCHAR(30) NOT NULL CHECK (type IN ('SSM','PTU')),
  reference VARCHAR(100) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_by INTEGER NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (business_id,type),
  FOREIGN KEY (business_id) REFERENCES pasor_kita.businesses(id),
  FOREIGN KEY (reviewed_by) REFERENCES pasor_kita.users(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id INTEGER NOT NULL,
  business_id INTEGER NULL,
  category_id INTEGER NOT NULL,
  title VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  price DECIMAL(10,2) NOT NULL CHECK (price > 0),
  stock INTEGER NOT NULL DEFAULT 1 CHECK (stock >= 0),
  campus VARCHAR(30) NOT NULL CHECK (campus IN ('Parit Raja','Pagoh')),
  pickup_location VARCHAR(160) NOT NULL,
  item_condition VARCHAR(60) NOT NULL,
  image_path VARCHAR(255) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived','removed')),
  is_sample BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (seller_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (business_id) REFERENCES pasor_kita.businesses(id),
  FOREIGN KEY (category_id) REFERENCES pasor_kita.categories(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  buyer_id INTEGER NOT NULL,
  seller_id INTEGER NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','ready','completed','cancelled')),
  pickup_details VARCHAR(300) NOT NULL,
  total DECIMAL(14,2) NOT NULL CHECK (total > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ NULL,
  FOREIGN KEY (buyer_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (seller_id) REFERENCES pasor_kita.users(id)

);
CREATE TABLE IF NOT EXISTS pasor_kita.order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL UNIQUE,
  product_id INTEGER NOT NULL,
  product_title VARCHAR(100) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (order_id) REFERENCES pasor_kita.orders(id),
  FOREIGN KEY (product_id) REFERENCES pasor_kita.products(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL,
  author_id INTEGER NOT NULL,
  kind VARCHAR(30) NOT NULL CHECK (kind IN ('item','seller','buyer')),
  target_user_id INTEGER NULL,
  product_id INTEGER NOT NULL,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment VARCHAR(600) NOT NULL,
  hidden BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (order_id,author_id,kind),
  FOREIGN KEY (order_id) REFERENCES pasor_kita.orders(id),
  FOREIGN KEY (author_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (target_user_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (product_id) REFERENCES pasor_kita.products(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.favorites (
  user_id INTEGER NOT NULL,
  product_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id,product_id),
  FOREIGN KEY (user_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (product_id) REFERENCES pasor_kita.products(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL,
  sender_id INTEGER NOT NULL,
  recipient_id INTEGER NOT NULL,
  body VARCHAR(1000) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (product_id) REFERENCES pasor_kita.products(id),
  FOREIGN KEY (sender_id) REFERENCES pasor_kita.users(id),
  FOREIGN KEY (recipient_id) REFERENCES pasor_kita.users(id)
);
CREATE TABLE IF NOT EXISTS pasor_kita.sessions (
  sid VARCHAR(128) NOT NULL PRIMARY KEY,
  data JSONB NOT NULL,
  expires BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS catalogue ON pasor_kita.products(status,campus,category_id);
CREATE INDEX IF NOT EXISTS buyer_orders ON pasor_kita.orders(buyer_id,created_at);
CREATE INDEX IF NOT EXISTS seller_orders ON pasor_kita.orders(seller_id,status);
CREATE INDEX IF NOT EXISTS mailbox ON pasor_kita.messages(recipient_id,created_at);
CREATE INDEX IF NOT EXISTS session_expiry ON pasor_kita.sessions(expires);
